export const getLanguage=()=>language;
export const t=value=>lookup.get(value)?.[language]??value;
const escapeRegex=value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const pattern=new RegExp([...lookup.keys()].sort((a,b)=>b.length-a.length).map(escapeRegex).join('|'),'gu');
export function ui(strings,...values){
 let inTag=false,output='';
 for(let i=0;i<strings.length;i++){
  let text='';
  const flush=()=>{output+=inTag?text:text.replace(pattern,match=>t(match));text='';};
  for(const char of strings[i]){
   if(char==='<'){flush();inTag=true;text+=char;}
   else if(char==='>'){text+=char;flush();inTag=false;}
   else text+=char;
  }
  flush();if(i<values.length)output+=values[i];
 }
 return output;
}
