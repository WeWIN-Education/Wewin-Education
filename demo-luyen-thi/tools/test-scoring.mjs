import assert from 'node:assert/strict';
import {exams,correct,grade,validateSubmission} from '../server/scoring.mjs';
const exam=exams.find(e=>e.id==='movers-06');
const answers=Object.fromEntries(['reading','listening'].flatMap(skill=>exam[skill].filter(p=>!p.manual).flatMap(p=>p.painting?[[p.id,Object.fromEntries(p.questions.map(q=>[q.answer.target,{color:q.answer.color,word:q.answer.word}]))]]:p.matchKey?[[p.id,p.matchKey]]:p.questions.map(q=>[q.id,q.answer]))));
assert.equal(grade(exam,validateSubmission(exam,{answers}).answers).total,100);
assert.equal(grade(exam,{}).total,0);
assert.equal(correct(exam.reading[0].questions[0],' '+exam.reading[0].questions[0].answer.toUpperCase()+' '),true);
assert.equal(correct(exam.listening[1].questions[1],' '+exam.listening[1].questions[1].answer.toUpperCase()+' '),true);
const colour=exam.listening[4].questions.find(q=>q.answer.color);
assert.equal(correct(colour,{target:colour.answer.target,color:colour.answer.color}),true);
assert.equal(correct(colour,{target:'wrong-target',color:colour.answer.color}),false);
console.log('PASS: current Movers scoring supports perfect, empty, normalized text, picture matching and colour answers.');
